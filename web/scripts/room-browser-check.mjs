// Run against a local dev server. Uses fresh browser contexts, never the owner's profile.
// ROOM_PLAYWRIGHT_PACKAGE can point to an already installed Playwright package.
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.ROOM_PLAYWRIGHT_PACKAGE || 'playwright');
const out = resolve('../docs/room'); await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const failures = [], checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
  const page = await context.newPage(); page.on('pageerror', e => failures.push(e.message));
  await page.goto('http://localhost:3000/room?demo=1');
  await page.locator('canvas[data-room-rendered="true"]').waitFor({ timeout: 30000 });
  await page.screenshot({ path: resolve(out, 'desktop-empty.png'), fullPage: true });
  await page.getByRole('button', { name: 'Рассказать о дне', exact: true }).click();
  await page.getByLabel('Сегодня', { exact: true }).fill('Сегодня показал проект другу. Волновался, но получил полезный отзыв.');
  await page.getByRole('button', { name: 'Подобрать предмет и заголовок' }).click();
  assert.equal(await page.getByLabel('Предмет', { exact: true }).inputValue(), 'model');
  await page.getByLabel('Один шаг на завтра', { exact: true }).fill('Закончить первую версию');
  await page.getByRole('button', { name: 'Сохранить воспоминание' }).click();
  await page.getByRole('button', { name: 'Исправить запись или интерпретацию' }).waitFor();
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await page.reload();
  await page.locator('canvas[data-room-rendered="true"]').waitFor();
  await page.getByRole('button', { name: /Макет проекта.*Сегодня показал проект другу/ }).waitFor();
  checks.push('create, interpret, memory, goal and reload');
  for (const resident of ['Скептик', 'Союзник', 'Бунтарь']) {
    await page.getByRole('button', { name: new RegExp(`^${resident}`) }).click();
    await page.getByLabel('Сообщение жителю').fill('Как выбрать следующий шаг?');
    await page.getByRole('button', { name: 'Отправить', exact: true }).click();
    await page.locator('[data-speech-resident] p[aria-hidden="true"]').filter({ hasText: 'В записи от' }).waitFor();
    await page.getByRole('button', { name: 'Закончить разговор', exact: true }).click();
    await page.locator('canvas[data-focused-resident=""]').waitFor();
  }
  checks.push('three distinct resident conversations referencing saved memory');
  await page.screenshot({ path: resolve(out, 'desktop-lived-in.png'), fullPage: true });
  await page.locator('canvas').click({ position: { x: 568, y: 350 } });
  await page.getByRole('dialog').getByRole('heading', { name: 'Бунтарь', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Закончить разговор', exact: true }).click();
  await page.locator('canvas[data-focused-resident=""]').waitFor();
  await page.locator('canvas').click({ position: { x: 307, y: 286 } });
  await page.getByRole('button', { name: 'Исправить запись или интерпретацию' }).waitFor();
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click();
  checks.push('3D raycasting opens resident and memory directly from scene');
  const canvas = page.locator('canvas'); await canvas.click({ position: { x: 450, y: 220 } });
  const before = Number(await canvas.getAttribute('data-camera-z'));
  await page.keyboard.down('KeyW'); await page.waitForTimeout(700); await page.keyboard.up('KeyW'); await page.waitForTimeout(300);
  const after = Number(await canvas.getAttribute('data-camera-z')); assert.ok(after < before - .1, `Camera did not move: ${before} -> ${after}`);
  await page.getByRole('button', { name: 'Вернуться ко входу' }).click(); checks.push('first-person keyboard movement');
  await page.getByRole('button', { name: 'Тихий дождь', exact: true }).click();
  await page.screenshot({ path: resolve(out, 'desktop-rain.png'), fullPage: true });
  await page.getByRole('button', { name: /Макет проекта.*Сегодня показал проект другу/ }).click();
  await page.getByRole('button', { name: 'Исправить запись или интерпретацию' }).click();
  await page.getByLabel('Название воспоминания').fill('Исправленное воспоминание');
  await page.getByLabel('Предмет', { exact: true }).selectOption('book');
  await page.getByRole('button', { name: 'Сохранить воспоминание' }).click();
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click();
  const corrected = await page.evaluate(() => JSON.parse(sessionStorage.getItem('overman.private-room.v1.demo')));
  assert.equal(corrected.entries[0].kind, 'book'); assert.ok(Object.values(corrected.chats).every(messages => messages.length === 0));
  checks.push('correction updates object and purges stale conversations');
  await page.getByRole('button', { name: /Книга открытий.*Исправленное воспоминание/ }).click();
  await page.getByRole('button', { name: 'Удалить воспоминание', exact: true }).click();
  await page.getByRole('button', { name: 'Да, удалить', exact: true }).click();
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await page.reload(); await page.getByText('Пока здесь чистый лист', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem('overman.living-tower.v1')), null);
  assert.equal(await page.evaluate(() => localStorage.getItem('overman.private-room.v1')), null);
  checks.push('delete persists, island and personal room untouched');
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, reducedMotion: 'reduce' });
  const phone = await mobile.newPage(); phone.on('pageerror', e => failures.push(e.message));
  await phone.goto('http://localhost:3000/room?demo=1'); await phone.locator('canvas[data-room-rendered="true"]').waitFor();
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await phone.screenshot({ path: resolve(out, 'mobile.png'), fullPage: true });
  await phone.getByRole('button', { name: 'Рассказать о дне', exact: true }).click();
  await phone.getByLabel('Сегодня', { exact: true }).fill('Сегодня прочитал книгу и отдохнул.');
  await phone.getByRole('button', { name: 'Подобрать предмет и заголовок' }).click();
  await phone.getByRole('button', { name: 'Сохранить воспоминание' }).click();
  await phone.getByRole('button', { name: 'Исправить запись или интерпретацию' }).waitFor();
  await phone.screenshot({ path: resolve(out, 'mobile-memory.png') });
  await phone.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await phone.getByRole('button', { name: 'Идти вперёд', exact: true }).scrollIntoViewIfNeeded();
  const pad = await phone.getByRole('button', { name: 'Идти вперёд', exact: true }).boundingBox();
  const phoneBefore = Number(await phone.locator('canvas').getAttribute('data-camera-z'));
  await phone.mouse.move(pad.x + pad.width / 2, pad.y + pad.height / 2); await phone.mouse.down(); await phone.waitForTimeout(700); await phone.mouse.up(); await phone.waitForTimeout(300);
  assert.ok(Number(await phone.locator('canvas').getAttribute('data-camera-z')) < phoneBefore - .1);
  checks.push('on-screen movement pad on mobile viewport');
  checks.push('mobile layout, entry form and memory modal');
  assert.deepEqual(failures, []);
  await writeFile(resolve(out, 'browser-check.json'), JSON.stringify({ date: new Date().toISOString(), checks, pageErrors: failures }, null, 2));
  console.log(JSON.stringify({ checks, pageErrors: failures, screenshots: out }, null, 2));
} finally { await browser.close(); }
